import type { Speaker } from '../types';

/**
 * Кто сейчас держит слово.
 *
 * Нужен из-за акустики: если звук встречи идёт из динамиков, микрофон
 * слышит и коллег тоже. Микрофон запинен на один язык, поэтому чужая
 * речь превращается в бессмысленный набор слов — и уходит в лог как
 * реплика ведущего, а в субтитры залу как его перевод. Выглядит это
 * как «приложение сошло с ума», хотя виновата комната.
 *
 * Правило простое и совпадает с тем, как люди разговаривают:
 * **говорит тот, кто начал раньше.** Пока он не замолчал, второй канал
 * молчит тоже. Никаких приоритетов по важности — кто первый, тот и прав.
 *
 * Решение принимает сам провайдер в момент РЕЧИ, а не в момент прихода
 * текста: чанковый канал отдаёт результат через несколько секунд, когда
 * слово может уже перейти к другому.
 *
 * Побочная выгода: подавленный чанк не отправляется вовсе, то есть
 * не расходует лимит.
 */

/** Сколько слово остаётся за говорившим после последнего признака речи.
 *  Короткие паузы внутри фразы не должны отдавать слово соседу. */
const HOLD_TAIL_MS = 1200;

let holder: Speaker | null = null;
let lastActivity = 0;

function free(now: number): boolean {
  return holder === null || now - lastActivity > HOLD_TAIL_MS;
}

/** Признак того, что канал сейчас слышит речь. Вызывается часто. */
export function claimFloor(who: Speaker): void {
  const now = performance.now();
  if (free(now) || holder === who) {
    holder = who;
    lastActivity = now;
  }
}

/** Можно ли этому каналу писать прямо сейчас. */
export function holdsFloor(who: Speaker): boolean {
  return free(performance.now()) || holder === who;
}

/** Кто держит слово — для индикации в интерфейсе. */
export function floorHolder(): Speaker | null {
  return free(performance.now()) ? null : holder;
}

export function releaseFloor(): void {
  holder = null;
  lastActivity = 0;
}
